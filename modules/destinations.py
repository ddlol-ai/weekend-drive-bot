def _week_index(today: date) -> int:
    iso = today.isocalendar()
    return iso[0] * 53 + iso[1]


def pick_weekly(destinations: List[Destination], today: date, seed: int) -> Destination:
    """주차 기반 순환 선택: 한 바퀴 돌 때까지 같은 곳이 반복되지 않음"""
    order = list(destinations)
    random.Random(seed).shuffle(order)
    return order[_week_index(today) % len(order)]
